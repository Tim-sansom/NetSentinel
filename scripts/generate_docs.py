"""
NetSentinel Automated Documentation Generator

This build script parses the Python agent code and PHP backend code 
to auto-generate a comprehensive DEVELOPER_GUIDE.md file.

It uses Python's built-in AST (Abstract Syntax Tree) module to extract 
docstrings from Python files, and Regex to extract block comments (/** ... */) 
from PHP files. This ensures the documentation is always in sync with the code.
"""

import os
import ast
import re


def extract_python_docs(filepath: str) -> list:
    """
    Extracts docstrings from Python files using the AST module.
    
    AST parsing is safer and more accurate than Regex because it understands 
    Python syntax, ignoring commented-out code or strings inside functions.
    
    Args:
        filepath: The absolute path to the Python file.
        
    Returns:
        A list of formatted Markdown strings containing the docstrings.
    """
    with open(filepath, 'r', encoding='utf-8') as f:
        try:
            tree = ast.parse(f.read())
        except SyntaxError:
            return []  # Skip files with syntax errors
            
    docs = []
    
    # Extract module-level docstring
    if ast.get_docstring(tree):
        docs.append(f"### Module: {os.path.basename(filepath)}\n{ast.get_docstring(tree)}\n")
        
    # Walk the AST to find classes and functions
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            doc = ast.get_docstring(node)
            if doc:
                docs.append(f"#### `{node.name}`\n{doc}\n")
                
    return docs


def extract_php_docs(filepath: str) -> list:
    """
    Extracts block comments (/** ... */) from PHP files using Regex.
    
    Targets standard PHPDoc style comments to capture function and class 
    documentation without picking up standard single-line comments.
    
    Args:
        filepath: The absolute path to the PHP file.
        
    Returns:
        A list of formatted Markdown strings containing the comments.
    """
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
        
    # Regex to find /** ... */ blocks
    pattern = re.compile(r'/\*\*(.*?)\*/', re.DOTALL)
    matches = pattern.findall(content)
    
    docs = []
    if matches:
        docs.append(f"### File: {os.path.basename(filepath)}\n")
        for match in matches:
            # Clean up the comment formatting (remove leading asterisks)
            clean_doc = re.sub(r'^\s*\*\s?', '', match).strip()
            docs.append(f"```php\n{clean_doc}\n```\n")
            
    return docs


def main():
    """
    Main execution loop for the documentation generator.
    
    Traverses the 'agent' and 'public/api' directories, extracts documentation, 
    and writes it to a single DEVELOPER_GUIDE.md file in the project root.
    """
    output_file = "DEVELOPER_GUIDE.md"
    project_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    
    with open(output_file, 'w', encoding='utf-8') as out:
        out.write("# NetSentinel Developer Documentation\n\n")
        out.write("*Auto-generated by `scripts/generate_docs.py`. Do not edit manually.*\n\n")
        
        # 1. Parse Python Agent
        out.write("## 1. Python Agent Architecture\n\n")
        agent_dir = os.path.join(project_root, "agent")
        if os.path.exists(agent_dir):
            for root, _, files in os.walk(agent_dir):
                for file in files:
                    if file.endswith(".py"):
                        filepath = os.path.join(root, file)
                        docs = extract_python_docs(filepath)
                        if docs:
                            out.write("\n".join(docs))
                            out.write("---\n\n")
        else:
            out.write("Agent directory not found.\n\n")

        # 2. Parse PHP API
        out.write("## 2. PHP Backend API\n\n")
        api_dir = os.path.join(project_root, "public", "api")
        if os.path.exists(api_dir):
            for root, _, files in os.walk(api_dir):
                for file in files:
                    if file.endswith(".php"):
                        filepath = os.path.join(root, file)
                        docs = extract_php_docs(filepath)
                        if docs:
                            out.write("\n".join(docs))
                            out.write("---\n\n")
        else:
            out.write("API directory not found.\n\n")

    print(f"Documentation successfully generated: {os.path.abspath(output_file)}")


if __name__ == "__main__":
    main()