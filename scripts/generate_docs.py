"""
NetSentinel Automated Documentation Generator

This build script parses the Python agent code and PHP backend code 
to auto-generate a comprehensive DEVELOPER_GUIDE.md file.

It uses Python's built-in AST (Abstract Syntax Tree) module to extract 
docstrings from Python files, and Regex to extract block comments (/** ... */) 
from PHP files. This ensures the documentation is always in sync with the code.
"""

import os
import ast
import re

def extract_python_docs(filepath: str) -> list:
    """Extracts docstrings from Python files using the AST module."""
    with open(filepath, 'r', encoding='utf-8') as f:
        try:
            tree = ast.parse(f.read())
        except SyntaxError:
            return []
            
    docs = []
    if ast.get_docstring(tree):
        docs.append(f"### Module: {os.path.basename(filepath)}\n{ast.get_docstring(tree)}\n")
        
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            doc = ast.get_docstring(node)
            if doc:
                docs.append(f"#### `{node.name}`\n{doc}\n")
                
    return docs

def extract_php_docs(filepath: str) -> list:
    """Extracts block comments (/** ... */) from PHP files using Regex."""
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
        
    # Regex to find /** ... */ blocks
    pattern = re.compile(r'/\*\*(.*?)\*/', re.DOTALL)
    matches = pattern.findall(content)
    
    docs = []
    if matches:
        docs.append(f"### File: {os.path.basename(filepath)}\n")
        for match in matches:
            # Clean up the comment formatting (remove leading asterisks)
            clean_doc = re.sub(r'^\s*\*\s?', '', match).strip()
            docs.append(f"```php\n{clean_doc}\n```\n")
            
    return docs

def scan_directory_for_docs(target_dir: str, file_ext: str, extractor_func) -> list:
    """Helper function to recursively scan a directory and extract docs."""
    all_docs = []
    if not os.path.exists(target_dir):
        return all_docs
        
    for root, _, files in os.walk(target_dir):
        for file in files:
            if file.endswith(file_ext):
                filepath = os.path.join(root, file)
                docs = extractor_func(filepath)
                if docs:
                    all_docs.append((filepath, docs))
    return all_docs

def main():
    output_file = "DEVELOPER_GUIDE.md"
    project_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    
    with open(output_file, 'w', encoding='utf-8') as out:
        out.write("# NetSentinel Developer Documentation\n\n")
        out.write("*Auto-generated by `scripts/generate_docs.py`. Do not edit manually.*\n\n")
        
        # ==========================================
        # 1. Python Agent & Scripts Architecture
        # ==========================================
        out.write("## 1. Python Agent & Scripts Architecture\n\n")
        
        python_dirs = [
            ("agent", "Core Agent & Configuration"),
            ("agent/checks", "Security Health Checks"),
            ("collector", "Docker/Legacy Collector Script"),
            ("scripts", "Utility & Discovery Scripts")
        ]
        
        for dir_name, section_title in python_dirs:
            out.write(f"### {section_title}\n\n")
            target_dir = os.path.join(project_root, dir_name)
            
            docs_found = scan_directory_for_docs(target_dir, ".py", extract_python_docs)
            if docs_found:
                # Sort by filename for consistent, predictable output
                docs_found.sort(key=lambda x: x[0])
                for filepath, docs in docs_found:
                    out.write("\n".join(docs))
                    out.write("---\n\n")
            else:
                out.write(f"*No Python files with docstrings found in {dir_name}.*\n\n")

        # ==========================================
        # 2. PHP Backend API & Core Logic
        # ==========================================
        out.write("## 2. PHP Backend API & Core Logic\n\n")
        
        php_dirs = [
            ("public", "Main Dashboard Pages"),
            ("public/api", "REST API Endpoints"),
            ("public/includes", "Core Backend Logic (Auth, DB, Audit)"),
            ("cronjobs", "Cronjobs & Maintenance Scripts")
        ]
        
        for dir_name, section_title in php_dirs:
            out.write(f"### {section_title}\n\n")
            target_dir = os.path.join(project_root, dir_name)
            
            docs_found = scan_directory_for_docs(target_dir, ".php", extract_php_docs)
            if docs_found:
                docs_found.sort(key=lambda x: x[0])
                for filepath, docs in docs_found:
                    out.write("\n".join(docs))
                    out.write("---\n\n")
            else:
                out.write(f"*No PHP files with block comments found in {dir_name}.*\n\n")

    print(f"✅ Documentation successfully generated: {os.path.abspath(output_file)}")

if __name__ == "__main__":
    main()